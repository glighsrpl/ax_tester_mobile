def get_rule_name_from_axe_tags(tags: list[str]) -> str:
    best_level = 4
    rule_name = "best-practice"

    for tag in tags:
        level = WCAG_LEVEL_MAPPER.get(tag, best_level)
        if level < best_level:
            best_level = level
            rule_name = WCAG_RULE_MAPPER[tag]

    return rule_name


def get_wcag_level(wcag_rule: object) -> str:
    if isinstance(wcag_rule, str):
        match = re.search(r"level\s+(AAA|AA|A)\b", wcag_rule, flags=re.IGNORECASE)
        if match:
            return match.group(1).upper()
    return "AAA"
